function renderDailyProgress() {

    const today =
        new Date().toISOString().slice(0, 10);

    const completedToday =
        currentUser.completedLessons.filter(item =>
            item.date === today
        ).length;

    const percent =
        Math.min(100, Math.round(
            (completedToday / 3) * 100
        ));

    document.getElementById("dailyPercent").textContent =
        `${percent}%`;

    document.getElementById("dailyLessons").textContent =
        `${Math.min(completedToday,3)} / 3`;

    document.getElementById("dailyCircle").style.background =
        `conic-gradient(var(--primary) ${percent * 3.6}deg, #e8ecf4 ${percent * 3.6}deg)`;

}


