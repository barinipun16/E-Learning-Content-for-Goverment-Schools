function completeLesson(subjectId, index) {

    const key =
        `${currentUser.classNo}_${subjectId}_${index}`;

    const exists =
        currentUser.completedLessons.some(
            item => item.key === key
        );

    if (!exists) {

        currentUser.completedLessons.push({
            key,
            date: new Date().toISOString().slice(0, 10)
        });

        saveUser();

        showToast(
            translations[currentLanguage].lessonCompletedMessage
        );

    }

    openLesson(subjectId, index);

    renderDashboard();
    renderProgress();

}


function isLessonCompleted(classNo, subjectId, index) {

    const key =
        `${classNo}_${subjectId}_${index}`;

    return currentUser.completedLessons.some(
        item => item.key === key
    );

}


