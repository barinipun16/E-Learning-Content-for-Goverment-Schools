/* =========================================================
   PROGRESS
   ========================================================= */

function renderProgress() {

    const total =
        getTotalLessons();

    const completed =
        currentUser.completedLessons.length;

    const overall =
        total
            ? Math.round((completed / total) * 100)
            : 0;

    document.getElementById("overallCircleText").textContent =
        `${overall}%`;

    document.getElementById("overallCircle").style.background =
        `conic-gradient(
            var(--primary) ${overall * 3.6}deg,
            #e8ecf4 ${overall * 3.6}deg
        )`;


    const list =
        document.getElementById("subjectProgressList");

    list.innerHTML = "";

    Object.keys(getClassLessons()).forEach(subjectId => {

        const lessons =
            getClassLessons()[subjectId];

        const completedSubject =
            lessons.filter((_, index) =>
                isLessonCompleted(
                    currentUser.classNo,
                    subjectId,
                    index
                )
            ).length;

        const percent =
            Math.round(
                (completedSubject / lessons.length) * 100
            );

        list.innerHTML += `

            <div class="progress-subject-row">

                <div class="progress-subject-top">

                    <strong>
                        ${subjectName(subjectId)}
                    </strong>

                    <span>
                        ${completedSubject}/${lessons.length}
                    </span>

                </div>

                <div class="progress-subject-bar">

                    <div style="width:${percent}%"></div>

                </div>

            </div>

        `;

    });

}


/* =========================================================
   SEARCH
   ========================================================= */

function handleSearch(e) {

    const query =
        e.target.value.trim().toLowerCase();

    if (!query) {

        if (currentPage === "search") {
            showPage("dashboard");
        }

        return;

    }

    showPage("search");

    const results = [];

    const classData = getClassLessons();

    Object.keys(classData).forEach(subjectId => {

        classData[subjectId].forEach((lesson, index) => {

            const title =
                lesson.title[currentLanguage];

            const description =
                lesson.description[currentLanguage];

            if (
                title.toLowerCase().includes(query) ||
                description.toLowerCase().includes(query)
            ) {

                results.push({
                    type: translations[currentLanguage].lesson,
                    title,
                    description,
                    action: () =>
                        openLesson(subjectId, index)
                });

            }

        });

    });


    certificateCourses.forEach(course => {

        const title =
            course.title[currentLanguage];

        const description =
            course.description[currentLanguage];

        if (
            title.toLowerCase().includes(query) ||
            description.toLowerCase().includes(query)
        ) {

            results.push({
                type: translations[currentLanguage].course,
                title,
                description,
                action: () =>
                    openCourse(course.id)
            });

        }

    });


    renderSearchResults(results, query);

}


function renderSearchResults(results, query) {

    const container =
        document.getElementById("searchResults");

    document.getElementById("searchSummary").textContent =
        `${translations[currentLanguage].searchFor} "${query}"`;

    if (!results.length) {

        container.innerHTML = `

            <div class="content-card">

                <h3>
                    ${translations[currentLanguage].noResults}
                </h3>

            </div>

        `;

        return;

    }


    container.innerHTML = results.map((result, index) => `

        <div
            class="search-result"
            data-result="${index}">

            <span class="search-type">
                ${result.type}
            </span>

            <div>
                <h3>
                    ${result.title}
                </h3>

                <p>
                    ${result.description}
                </p>
            </div>

        </div>

    `).join("");


    container.querySelectorAll(".search-result")
        .forEach((element, index) => {

            element.addEventListener("click", () => {

                results[index].action();

            });

        });

}


/* =========================================================
   THEME
   ========================================================= */

function setupTheme() {

    const savedTheme =
        localStorage.getItem("edubridge_theme");

    if (savedTheme === "dark") {
        document.body.classList.add("dark");
    }

    document
        .getElementById("themeToggle")
        .addEventListener("click", toggleTheme);

}


function toggleTheme() {

    document.body.classList.toggle("dark");

    localStorage.setItem(
        "edubridge_theme",
        document.body.classList.contains("dark")
            ? "dark"
            : "light"
    );

}


