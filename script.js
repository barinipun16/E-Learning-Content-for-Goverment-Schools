function setupAuth() {

    document.getElementById("showSignup").addEventListener("click", () => {

        document.getElementById("loginBox").classList.add("hidden");
        document.getElementById("signupBox").classList.remove("hidden");

    });

    document.getElementById("showLogin").addEventListener("click", () => {

        document.getElementById("signupBox").classList.add("hidden");
        document.getElementById("loginBox").classList.remove("hidden");

    });


    document.getElementById("authLanguage").addEventListener("change", e => {

        currentLanguage = e.target.value;
        translateAuth();

    });


    document.getElementById("loginForm").addEventListener("submit", e => {

        e.preventDefault();

        const username =
            document.getElementById("loginUsername").value.trim();

        const password =
            document.getElementById("loginPassword").value;

        const users = getUsers();

        if (!users[username] || users[username].password !== password) {

            showFormMessage(
                "loginMessage",
                translations[currentLanguage].invalidLogin,
                "error"
            );

            return;
        }

        currentUser = users[username];

        currentLanguage =
            localStorage.getItem(`edubridge_language_${username}`) || "en";

        saveCurrentUser(username);

        openApp();

    });


    document.getElementById("signupForm").addEventListener("submit", e => {

        e.preventDefault();

        const username =
            document.getElementById("signupUsername").value.trim();

        const classNo =
            document.getElementById("signupClass").value;

        const password =
            document.getElementById("signupPassword").value;

        const confirm =
            document.getElementById("signupConfirmPassword").value;

        const users = getUsers();

        if (users[username]) {

            showFormMessage(
                "signupMessage",
                translations[currentLanguage].usernameExists,
                "error"
            );

            return;
        }

        if (!classNo) {

            showFormMessage(
                "signupMessage",
                translations[currentLanguage].chooseClass,
                "error"
            );

            return;
        }

        if (password !== confirm) {

            showFormMessage(
                "signupMessage",
                translations[currentLanguage].passwordMismatch,
                "error"
            );

            return;
        }

        if (username.length < 3) {

            showFormMessage(
                "signupMessage",
                "Username must contain at least 3 characters.",
                "error"
            );

            return;
        }

        users[username] = createUser(
            username,
            password,
            Number(classNo)
        );

        saveUsers(users);

        showFormMessage(
            "signupMessage",
            translations[currentLanguage].accountCreated,
            "success"
        );

        document.getElementById("signupForm").reset();

        setTimeout(() => {

            document.getElementById("signupBox").classList.add("hidden");
            document.getElementById("loginBox").classList.remove("hidden");

            document.getElementById("loginUsername").value = username;

        }, 800);

    });


    document.getElementById("logoutBtn").addEventListener("click", logout);

}


