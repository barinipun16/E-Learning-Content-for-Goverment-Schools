function startQuiz(subjectId) {

    const questions =
        quizzes[subjectId] || [];

    if (!questions.length) {

        showToast("Quiz content is being prepared.");
        return;

    }

    currentQuiz = {
        subjectId,
        questions,
        current: 0,
        score: 0
    };

    renderQuizQuestion();

    document
        .getElementById("quizRunner")
        .scrollIntoView({
            behavior: "smooth"
        });

}


function renderQuizQuestion() {

    const runner =
        document.getElementById("quizRunner");

    runner.classList.remove("hidden");

    const q =
        currentQuiz.questions[currentQuiz.current];

    const questionNumber =
        currentQuiz.current + 1;

    const total =
        currentQuiz.questions.length;

    runner.innerHTML = `

        <div>

            <strong>
                ${translations[currentLanguage].quizTitle}
            </strong>

            <span style="float:right;font-size:11px;color:var(--muted)">
                ${questionNumber} / ${total}
            </span>

        </div>

        <div class="quiz-progress">

            <div style="
                width:${(questionNumber / total) * 100}%
            "></div>

        </div>

        <div class="quiz-question">
            ${q.q[currentLanguage]}
        </div>

        <div class="quiz-options">

            ${q.options[currentLanguage].map((option, index) => `

                <button
                    class="quiz-option"
                    data-answer="${index}">

                    ${option}

                </button>

            `).join("")}

        </div>
    `;


    runner.querySelectorAll(".quiz-option")
        .forEach(btn => {

            btn.addEventListener("click", () => {

                const selected =
                    Number(btn.dataset.answer);

                if (
                    selected ===
                    q.answer
                ) {
                    currentQuiz.score++;
                }

                currentQuiz.current++;

                if (
                    currentQuiz.current <
                    currentQuiz.questions.length
                ) {

                    renderQuizQuestion();

                } else {

                    finishQuiz();

                }

            });

        });

}


function finishQuiz() {

    const total =
        currentQuiz.questions.length;

    const score =
        Math.round(
            (currentQuiz.score / total) * 100
        );

    const subjectId =
        currentQuiz.subjectId;

    currentUser.quizScores[subjectId] =
        Math.max(
            currentUser.quizScores[subjectId] || 0,
            score
        );

    saveUser();

    const runner =
        document.getElementById("quizRunner");

    runner.innerHTML = `

        <div class="quiz-result">

            <span class="section-label">
                ${translations[currentLanguage].quizTitle}
            </span>

            <h2>
                ${
                    score >= 70
                    ? currentLanguage === "en"
                        ? "Great work!"
                        : currentLanguage === "hi"
                            ? "बहुत अच्छा!"
                            : "उत्तम काम!"
                    : currentLanguage === "en"
                        ? "Keep practising!"
                        : currentLanguage === "hi"
                            ? "अभ्यास जारी रखें!"
                            : "सराव सुरू ठेवा!"
                }
            </h2>

            <div class="quiz-score">
                ${score}%
            </div>

            <p>
                ${currentQuiz.score}
                /
                ${total}
            </p>

            <br>

            <button
                class="primary-btn"
                id="quizAgain">

                ${translations[currentLanguage].takeQuiz}

            </button>

        </div>
    `;

    document
        .getElementById("quizAgain")
        .addEventListener("click", () => {

            startQuiz(subjectId);

        });

    renderDashboard();

}


