function renderContinueLearning() {

    const lessons = getClassLessons();

    let selected = null;

    outer:
    for (const subjectId of Object.keys(lessons)) {

        for (let i = 0; i < lessons[subjectId].length; i++) {

            if (
                !isLessonCompleted(
                    currentUser.classNo,
                    subjectId,
                    i
                )
            ) {

                selected = {
                    subjectId,
                    index: i,
                    lesson: lessons[subjectId][i]
                };

                break outer;

            }

        }

    }


    if (!selected) {

        document.getElementById("continueTitle").textContent =
            currentLanguage === "en"
                ? "All lessons completed"
                : currentLanguage === "hi"
                    ? "सभी पाठ पूरे हो गए"
                    : "सर्व धडे पूर्ण झाले";

        document.getElementById("continueLesson").textContent =
            currentLanguage === "en"
                ? "Excellent work!"
                : currentLanguage === "hi"
                    ? "बहुत अच्छा!"
                    : "उत्तम काम!";

        document.getElementById("continueDescription").textContent =
            currentLanguage === "en"
                ? "Explore quizzes and certificate courses next."
                : currentLanguage === "hi"
                    ? "अब प्रश्नोत्तरी और प्रमाणपत्र पाठ्यक्रम देखें।"
                    : "आता प्रश्नमंजुषा आणि प्रमाणपत्र अभ्यासक्रम पहा.";

        document.getElementById("continueProgress").style.width = "100%";
        document.getElementById("continueProgressText").textContent = "100%";

        return;
    }


    const lesson = selected.lesson;

    document.getElementById("continueTitle").textContent =
        lesson.title[currentLanguage];

    document.getElementById("continueSubject").textContent =
        subjectName(selected.subjectId);

    document.getElementById("continueLesson").textContent =
        lesson.title[currentLanguage];

    document.getElementById("continueDescription").textContent =
        lesson.description[currentLanguage];

    const total =
        getTotalLessons();

    const completed =
        currentUser.completedLessons.length;

    const progress =
        Math.round((completed / total) * 100);

    document.getElementById("continueProgress").style.width =
        `${progress}%`;

    document.getElementById("continueProgressText").textContent =
        `${progress}%`;

    document.getElementById("continueBtn").textContent =
        completed > 0
            ? translations[currentLanguage].continue
            : translations[currentLanguage].startLearning;

    document.getElementById("continueBtn").onclick = () => {

        openLesson(
            selected.subjectId,
            selected.index
        );

    };

}


